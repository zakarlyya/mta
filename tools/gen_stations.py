"""Generate Sources/MTABar/StationsData.swift from MTA static data.

Usage: python3 tools/gen_stations.py
"""

import csv
import io
import json
import pathlib
import urllib.request
import zipfile
from collections import defaultdict

GTFS_URL = "https://rrgtfsfeeds.s3.amazonaws.com/gtfs_subway.zip"
STATIONS_URL = "https://data.ny.gov/api/views/39hk-dx4f/rows.csv?accessType=DOWNLOAD"
OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/MTABar/StationsData.swift"

ROUTE_ORDER = "1 2 3 4 5 6 7 A C E B D F M G J Z L N Q R W GS FS H SI".split()


def normalize(route):
    return route[:-1] if len(route) == 2 and route.endswith("X") else route


def fetch(url):
    with urllib.request.urlopen(url) as resp:
        return resp.read()


def main():
    gtfs = zipfile.ZipFile(io.BytesIO(fetch(GTFS_URL)))

    def rows(name):
        return csv.DictReader(io.TextIOWrapper(gtfs.open(name), encoding="utf-8-sig"))

    trip_route = {r["trip_id"]: normalize(r["route_id"]) for r in rows("trips.txt")}
    parent = {r["stop_id"]: r["parent_station"] or r["stop_id"] for r in rows("stops.txt")}

    routes = defaultdict(set)
    for r in rows("stop_times.txt"):
        route = trip_route.get(r["trip_id"])
        if route:
            routes[parent.get(r["stop_id"], r["stop_id"])].add(route)

    stations = []
    reader = csv.DictReader(io.StringIO(fetch(STATIONS_URL).decode("utf-8-sig")))
    for r in reader:
        sid = r["GTFS Stop ID"]
        served = routes.get(sid) or set(r["Daytime Routes"].split())
        stations.append({
            "id": sid,
            "name": r["Stop Name"],
            "line": r["Line"],
            "borough": r["Borough"],
            "routes": sorted(served, key=lambda x: ROUTE_ORDER.index(x) if x in ROUTE_ORDER else 99),
            "lat": float(r["GTFS Latitude"]),
            "lon": float(r["GTFS Longitude"]),
            "north": r["North Direction Label"] or "Northbound",
            "south": r["South Direction Label"] or "Southbound",
        })
    stations.sort(key=lambda s: (s["name"], s["line"]))

    payload = json.dumps(stations, separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(
        "// Generated by tools/gen_stations.py. Do not edit.\n"
        f'let stationsJSON = #"""\n{payload}\n"""#\n'
    )
    print(f"Wrote {len(stations)} stations to {OUT}")


if __name__ == "__main__":
    main()
